  String text(String key, [Map<String, Object> parameters = const {}]) {
    var value = _values[isAmharic ? 'am' : 'en']![key] ?? key;
    for (final entry in parameters.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

  String taskCount(int count) {
    if (isAmharic) return '$count ${text(count == 1 ? 'task' : 'tasks')}';
    return '$count ${text(count == 1 ? 'task' : 'tasks')}';
  }

  String tasksOverall(int count) => text('tasksOverall', {
    'count': count,
    'tasks': text(count == 1 ? 'task' : 'tasks'),
  });
